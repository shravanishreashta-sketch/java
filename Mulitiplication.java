public class Mulitiplication {
    public static void main(String[] args) {
        int num = 8; // The number for the multiplication table

        // Loop from 1 to 10 to print the table
        for (int i = 1; i <= 10; i++) {
            System.out.println(num + " x " + i + " = " + (num * i));
        }
    }
}
   

